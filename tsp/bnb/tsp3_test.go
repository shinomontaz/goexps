func TestTSP3(t *testing.T) {
	tests := []struct {
		name       string
		adj        [][]int64
		startPoint int
		lastPoint  int
	}{
		{
			name: "5 cities",
			adj: [][]int64{
				{math.MaxInt64, 10, 15, 20, 25},
				{10, math.MaxInt64, 35, 25, 30},
				{15, 35, math.MaxInt64, 30, 20},
				{20, 25, 30, math.MaxInt64, 15},
				{25, 30, 20, 15, math.MaxInt64},
			},
			startPoint: 0,
			lastPoint:  -1,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			bnbPath, _ := branches(tt.adj, tt.startPoint, tt.lastPoint)
			bruteForcePath, _ := heaps(tt.adj, tt.startPoint, tt.lastPoint)

			if !equalPaths(bnbPath, bruteForcePath) {
				t.Errorf("Branch and Bound path (%v) does not match Brute Force path (%v)", bnbPath, bruteForcePath)
			}
		})
	}
}

